#[test]
fn string_quoting_matches_go_yaml_v2() {
    let mut failures = Vec::new();
    for (input, expected) in VECTORS {
        let got = marshal_string(&Node::Map(vec![(Node::str("k"), Node::str(*input))]));
        if got != *expected {
            failures.push(format!("input {input:?}: got {got:?}, want {expected:?}"));
        }
    }
    assert!(
        failures.is_empty(),
        "{} mismatches:\n{}",
        failures.len(),
        failures.join("\n")
    );
}
